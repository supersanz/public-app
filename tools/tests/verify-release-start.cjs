const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('tools/tests/verify-growth.cjs','utf8').split('const {run,element,listeners,store,context}=fixture();')[0];
const sandbox={require,process,console};
vm.runInNewContext(source+';this.makeFixture=fixture;',sandbox);
const oldSandbox={require,process,console};
vm.runInNewContext(source.replaceAll('daily-quest-430-release-v1','daily-quest-430-v2')+';this.makeFixture=fixture;',oldSandbox);
const previous={logs:[],levelCurveVersion:3,petProgressVersion:2,playerResetEarned:-999999,questProfile:{version:1,onboardingCompleted:true},travelerJourney:{claimed:['sky','fly','academy','studyWork'],background:'sky'}};
const fresh=oldSandbox.makeFixture(previous);
assert.equal(fresh.run('player().lv'),1);
assert.equal(fresh.run('player().xp'),0);
assert.equal(fresh.run('data.logs.length'),0);
assert.equal(fresh.run('data.questProfile?.onboardingCompleted'),undefined);
assert.equal(fresh.run('data.disableScenePreview'),true);
const rewards=require(process.cwd()+'/scripts/reward-catalog.js');
assert.deepEqual(rewards.state(fresh.run('data.travelerJourney')), {version:2,claimed:[],background:'white',motion:'still'});
fresh.run('data.questProfile={version:1,onboardingCompleted:true};data.walkExp=50;persist()');
const reload=sandbox.makeFixture(JSON.parse(fresh.store['daily-quest-430-release-v1']));
assert.equal(reload.run('player().xp'),50);
assert.equal(reload.run('data.questProfile.onboardingCompleted'),true);
console.log('PASS release start: old test progress ignored, Lv1/0XP, no claimed rewards, onboarding, subsequent progress retained');
