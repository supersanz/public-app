const assert=require('node:assert/strict');
const quests=require('../../scripts/daily-quests.js');
const curve=require('../../scripts/experience-levels.js');
let data={logs:[]};const day='2026-09-28',next='2026-09-29';
const total=()=>data.logs.reduce((sum,l)=>sum+l.ids.reduce((s,id)=>s+l.exp[id],0),0);
assert(quests.save(data,day,1,true,40,()=>true));assert.equal(total(),40);
assert.equal(quests.save(data,day,1,true,40,()=>true),false,'stale double-check cannot award twice');
assert.equal(total(),40);
let reloaded=JSON.parse(JSON.stringify(data));assert(quests.status(reloaded,day,1).done);
assert(!quests.status(reloaded,next,1).done,'new day starts unchecked');
assert(quests.save(data,next,1,true,40,()=>true));assert.equal(total(),80);
assert(quests.save(data,next,1,false,40,()=>true));assert.equal(total(),40);assert(quests.status(data,day,1).done);
const snapshot=JSON.stringify(data);
assert(!quests.save(data,day,1,false,40,()=>false));assert.equal(JSON.stringify(data),snapshot,'failed cancellation rolls back');
assert(!quests.save(data,day,2,true,30,()=>false));assert.equal(JSON.stringify(data),snapshot,'failed save rolls back');
assert(quests.save(data,day,1,false,40,()=>true));assert.equal(total(),0);
for(let id=0;id<12;id++)assert(quests.save(data,day,id,true,40,()=>true));
assert.equal(curve.progress(total()).lv,2,'quest XP levels up the character');
assert(quests.save(data,day,11,false,40,()=>true));assert.equal(curve.progress(total()).lv,1);
data={logs:[{date:day,ids:[2],exp:{2:90},counts:{2:3}}]};
assert(quests.status(data,day,2).legacy);assert.equal(quests.status(data,day,2).xp,90);
assert(!quests.save(data,day,2,true,30,()=>true));assert(!quests.save(data,day,2,false,30,()=>true));assert.equal(total(),90,'old records are preserved');
assert(quests.save(data,day,3,true,40,()=>true));assert.equal(total(),130);
assert(quests.save(data,day,3,false,40,()=>true));assert.equal(total(),90);
console.log('PASS daily quests: duplicate guard, cancel, rollover, reload, legacy records, failed saves and level-up');
